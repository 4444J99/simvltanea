// Regenerates the configuration reference table in docs/authoring/LAB.md from the parameter registry.
// --check fails (exit 1) when the committed table is stale; --doc <path> targets another copy (used by the tests).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { configReferenceMarkdown, PARAMS } from '../app/params.js';

// src/simvltanea/lab/scripts -> repository root
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const at = process.argv.indexOf('--doc');
const doc = at > 0 && process.argv[at + 1] ? process.argv[at + 1] : join(root, 'docs', 'authoring', 'LAB.md');
const BEGIN = '<!-- BEGIN CONFIG REFERENCE (generated by src/simvltanea/lab/scripts/gen_config_reference.mjs; do not edit) -->';
const END = '<!-- END CONFIG REFERENCE -->';
const text = readFileSync(doc, 'utf8');
const a = text.indexOf(BEGIN), b = text.indexOf(END);
if (a < 0 || b < 0) throw new Error(`config reference markers missing in ${doc}`);
const body = `${BEGIN}\n\n_${PARAMS.length} parameters._\n\n${configReferenceMarkdown()}\n${END}`;
const next = text.slice(0, a) + body + text.slice(b + END.length);
if (process.argv.includes('--check')) {
  if (next !== text) {
    console.error('LAB.md config reference is stale: run node src/simvltanea/lab/scripts/gen_config_reference.mjs');
    process.exit(1);
  }
  console.log('LAB.md config reference is up to date');
} else { writeFileSync(doc, next); console.log(`wrote ${PARAMS.length} parameters`); }
