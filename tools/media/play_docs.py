def relation_formula_block() -> str:
    bits = play_rng.BITS_PER_UNIT
    return "\n".join([
        "```text",
        "field  = weighted mean of A(candidate, clip on other loop), neighbours weighted up",
        "grav   = (1 - independence) * field + independence * A(candidate, this loop's previous clip)",
        "         (previous clip = the clip the loop is showing when the pick is made, the one being replaced)",
        "logit  = strength * grav + anchor_pull * max A(candidate, anchor)",
        "         - novelty * coverage_pressure - recency * recency_penalty",
        f"draw weight = 2^({bits} * logit / temperature)      (integer table, SHA-256 draws)",
        "```",
        "",
        f"The scale matters. `BITS_PER_UNIT` is {bits}, so a logit gap of 1.0 at temperature 1 is {bits} bits of odds, "
        f"about {2 ** bits}:1 (`play_rng.weighted_pick` over evenly spaced draws measures about 259:1 because the "
        "table is rounded), not 2:1 as a plain base-2 softmax of the logit would give and not e:1 as a natural-base "
        f"softmax would. At temperature T the odds for a gap g are 2^({bits} * g / T). Strength, novelty and recency "
        "are all logit terms, so each is multiplied by the same scale.",
    ])


def _short_range(p: dict) -> str:
    if p["type"] == "number":
        return f"{p['min']:g} to {p['max']:g}"
    return _range(p)


