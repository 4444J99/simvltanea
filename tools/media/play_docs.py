TEST_ROOTS = (REPO_ROOT / "src" / "simvltanea" / "authoring", REPO_ROOT / "tools" / "media")
CITED_TEST = re.compile(r"`(test_[a-z0-9_]+(?:\.py)?|[A-Z][A-Za-z0-9]*Tests)`")
PRESET_MENTION = (re.compile(r"`([a-z][a-z_]*)` (?:preset|mode)s?\b"), re.compile(r"\b(?:preset|mode)s? `([a-z][a-z_]*)`"))
PRESET_LIST = re.compile(r"\bpresets? \(((?:[^()`]|`[^`]*`)*)\)")


def citation_problems(text: str, roots: tuple[Path, ...] = TEST_ROOTS) -> list[str]:
    """Every test, test class and test file the page cites in backticks that does not exist under ``roots``.

    ``test_x`` must be a ``def test_x(``, ``XxxTests`` a ``class XxxTests(`` and ``test_x.py`` a file, in the test
    sources beside the authoring code or under ``tools/media``. Empty when every citation exists.
    """
    files = [path for root in roots for path in sorted(root.glob("test_*.py"))]
    sources = "\n".join(path.read_text(encoding="utf-8") for path in files)
    names = {path.name for path in files}
    out = []
    for name in sorted(set(CITED_TEST.findall(text))):
        if name.endswith(".py"):
            found = name in names
        elif name.endswith("Tests"):
            found = re.search(rf"^class {name}\(", sources, re.M) is not None
        else:
            found = re.search(rf"def {name}\(", sources) is not None
        if not found:
            out.append(f"cited test does not exist: {name}")
    return out


def preset_name_problems(text: str) -> list[str]:
    """Backticked names the page presents as a preset or mode (``` `sticky` preset ```, ``` preset `sticky` ```,
    ``` presets (`drift`, `sticky`) ```) that are not in ``PRESETS``. Empty when every one is a real preset."""
    flat = " ".join(text.split())
    names = {m.group(1) for pattern in PRESET_MENTION for m in pattern.finditer(flat)}
    for group in PRESET_LIST.findall(flat):
        names |= set(re.findall(r"`([a-z][a-z_]*)`", group))
    return [f"not a preset: {name}" for name in sorted(names - set(PRESETS))]


def prose_problems(gravity: str, modes: str) -> list[str]:
    """Hand-written numbers that restate a code constant, compared with the code. Empty when all agree."""
    out: list[str] = []

    def check(label: str, found: list, expected: object) -> None:
        if not found:
            out.append(f"{label}: statement not found")
        out.extend(f"{label}: the page says {value!r}, the code has {expected!r}" for value in found if value != expected)

    check("component quantum", [int(x) for x in re.findall(r"steps of 10\^-(\d+)", gravity)],
          round(math.log10(ga.COMPONENT_SCALE)))
    check("prominence rule", [(int(a), int(b)) for a, b in re.findall(r"`(\d+)/\((\d+)\+rank\)`", gravity)],
          (int(ga.PROMINENCE_RANK),) * 2)
    check("softmax step", [int(x) for x in re.findall(r"1/(\d+)-bit steps", gravity)], len(play_rng.MANTISSA))
    check("weight range", [(int(a), int(b)) for a, b in re.findall(r"\(`relation\.weights`, (-?\d+) to (-?\d+)\)", gravity)],
          (int(ga.WEIGHT_RANGE[0]), int(ga.WEIGHT_RANGE[1])))
    check("result with no data", [int(x) for x in re.findall(r"result is exactly (\d+)", gravity)],
          round(ga.affinity({"id": "a"}, {"id": "b"}) * ga.AFFINITY_SCALE))
    local = re.search(r"^- Clips with only local features[^\n]*?renormalised", gravity, re.M)
    check("local-only components", [tuple(re.findall(r"`(\w+)`", local.group(0)))] if local else [],
          tuple(ga.LOCAL_ONLY_COMPONENTS))
    check("render segment limit", _ints(re.findall(r"(?:at most|more than) ([\d,]+) (?:render )?segments", modes)),
          composition.MAX_SEGMENTS)
    flat_modes = " ".join(modes.split())
    check("spans per loop limit", _ints(re.findall(r"(?:at most|more than|of) ([\d,]+) spans per loop", flat_modes)),
          composition.MAX_SEGMENTS)
    check("hold floor", [float(x) for x in re.findall(r"floor of ([\d.]+) s", modes)], play_config.MIN_HOLD)
    check("hold floor (timing section)", [float(x) for x in re.findall(r"drawn per change, at least ([\d.]+) s", flat_modes)],
          play_config.MIN_HOLD)
    candidates = next(p for p in describe_parameters() if p["path"] == "limits.max_candidates")
    check("max_candidates default", [int(x) for x in re.findall(r"\((\d+) by default\)", flat_modes + " ".join(gravity.split()))], candidates["default"])
    check("duration cap", _ints(re.findall(r"Durations are capped at ([\d,]+) s", flat_modes)), MAX_SECONDS)
    check("seed limit", [2 ** int(x) - 1 for x in re.findall(r"2\*\*(\d+) - 1", modes)], play_config.MAX_SAFE_SEED)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="rewrite the generated blocks in place")
    args = parser.parse_args(argv)
    status = 0
    texts = {}
    for doc, build in ((DOC, render), (GRAVITY_DOC, render_gravity)):
        current = doc.read_text(encoding="utf-8")
        texts[doc] = current
        fresh = build(current)
        if args.write:
            if fresh != current:
                doc.write_text(fresh, encoding="utf-8")
                texts[doc] = fresh
            print(f"{doc.relative_to(REPO_ROOT)} generated blocks written")
        elif fresh != current:
            print(f"{doc.relative_to(REPO_ROOT)} is out of date; run python3 -m tools.media.play_docs --write")
            status = 1
        else:
            print(f"{doc.relative_to(REPO_ROOT)} generated blocks match the code")
    for problem in prose_problems(texts[GRAVITY_DOC], texts[DOC]):
        print(f"quoted number differs from the code: {problem}")
        status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
