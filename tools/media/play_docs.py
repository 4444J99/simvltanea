def inert_block() -> str:
    rows = ["| Where | Settings with no effect | Why |", "| --- | --- | --- |"]
    rows += [f"| {_cell(where)} | {', '.join(f'`{name}`' for name in names)} | {_cell(why)} |"
             for _, where, names, why in INERT_ROWS]
    rows += ["", SYNCHRONIZED_NOTE]
    known = {p["path"] for p in describe_parameters()} | {"relation.weights.*"}
    unknown = [name for _, _, names, _ in INERT_ROWS for name in names if name not in known]
    if unknown:
        raise ValueError(f"inert settings that are not parameters: {unknown}")
    return "\n".join(rows)


def segment_durations(n: int, hold_min: float, clip_min: float) -> int:
    """Longest whole-second duration (up to 600) whose guaranteed bound stays within the limit."""
    rates = [loop["rate"] for loop in base_state_for(n)["loops"]]
    best = 0
    for seconds in range(1, MAX_SECONDS + 1):
        if render_segment_bound(rates, seconds, hold_min, clip_min, FPS) > LIMIT:
            break
        best = seconds
    return best


def typical_duration(n: int) -> int:
    """Longest duration, in whole multiples of 5 s (up to 600), whose estimate stays well under the limit."""
    rates = [loop["rate"] for loop in base_state_for(n)["loops"]]
    best = 0
    for seconds in range(5, MAX_SECONDS + 1, 5):
        if render_segment_estimate(rates, seconds, TYPICAL_HOLD_SECONDS, TYPICAL_CLIP_SECONDS) * TYPICAL_MARGIN > LIMIT:
            break
        best = seconds
    return best


def segments_block() -> str:
    rows = ["| Loops (N) | Typical estimate | Guaranteed: holds from 4 s, clips from 1.5 s | "
            "Guaranteed: holds from 12 s, clips from 1.5 s | Guaranteed: holds from 4 s, clips from 3 s |",
            "| --- | --- | --- | --- | --- |"]
    for n in range(2, 8):
        rows.append(f"| {n} | {typical_duration(n)} s | {segment_durations(n, 4.0, 1.5)} s | "
                    f"{segment_durations(n, 12.0, 1.5)} s | {segment_durations(n, 4.0, 3.0)} s |")
    return "\n".join(rows)


