def _cell(text: object) -> str:
    return str(text).replace("|", "\\|")


def _range(p: dict) -> str:
    kind = p["type"]
    if kind == "enum":
        return "one of " + ", ".join(f"`{c}`" for c in p["choices"])
    if kind == "integer":
        return f"integer {p['min']} to {p['max']}"
    if kind == "number":
        text = f"number {p['min']:g} to {p['max']:g}"
        if "zero_or_min" in p:
            text += f" (0 or at least {p['zero_or_min']:g})"
        return text
    if kind == "boolean":
        return "true or false"
    if kind == "id_list":
        return "list of clip ids"
    if kind == "flag_list":
        return "list of " + ", ".join(f"`{c}`" for c in p["choices"])
    if kind == "pin_list":
        return "list of [loop, clip] pairs"
    if kind == "seed":
        return "integer or string"
    raise ValueError(f"no documentation form for parameter type {kind!r}")


def _default(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ", ".join(f"`{v}`" for v in value) if value else "none"
    if isinstance(value, str):
        return f"`{value}`"
    return f"{value:g}" if isinstance(value, float) else str(value)


def parameters_block() -> str:
    entries = describe_parameters()
    out: list[str] = []
    for section in SECTIONS:
        rows = [p for p in entries if p["section"] == section]
        out += [f"### `{section}`", "", "| Parameter | Values | Default | Effect |", "| --- | --- | --- | --- |"]
        out += [f"| `{p['path']}` | {_cell(_range(p))} | {_cell(_default(p['default']))} | {_cell(p['description'])} |"
                for p in rows]
        out.append("")
    seed = next(p for p in entries if p["path"] == "seed")
    out += ["### `seed`", "", "| Parameter | Values | Default | Effect |", "| --- | --- | --- | --- |",
            f"| `seed` | {_range(seed)} | {_default(seed['default'])} | {_cell(seed['description'])} |"]
    covered = {p["path"] for p in entries if p["section"] in SECTIONS} | {"seed"}
    missing = [p["path"] for p in entries if p["path"] not in covered]
    if missing:
        raise ValueError(f"parameters without a documented section: {missing}")
    return "\n".join(out)


def presets_block() -> str:
    rows = ["| Preset | What it does |", "| --- | --- |"]
