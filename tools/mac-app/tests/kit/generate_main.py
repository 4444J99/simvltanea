#!/usr/bin/env python3
"""Regenerate tests/kit/main.swift, the suite registry (the Command Line Tools have no XCTest runner).

    python3 apps/macos/tests/kit/generate_main.py          # rewrite
    python3 apps/macos/tests/kit/generate_main.py --check  # exit 1 when the registry is stale
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def render() -> str:
    rows = []
    for source in sorted(HERE.glob('*_tests.swift')):
        text = source.read_text(encoding='utf-8')
        for cls in re.findall(r'final class (\w+): XCTestCase', text):
            body = text.split(f'final class {cls}: XCTestCase', 1)[1]
            for method in re.findall(r'\n    func (test\w+)\(\)', body):
                rows.append(f'    ("{cls}.{method}", {cls}.self, {{ try await ($0 as! {cls}).{method}() }}),')
    return ('// Generated by generate_main.py; do not edit by hand.\n'
            'import Foundation\n\n'
            'let registry: [(String, XCTestCase.Type, (XCTestCase) async throws -> Void)] = [\n'
            + '\n'.join(rows) + '\n]\n\n'
            'setvbuf(stdout, nil, _IOLBF, 0)\n'
            'let filter = CommandLine.arguments.dropFirst().first\n'
            'var ran = 0\n'
            'for (name, type, body) in registry where filter == nil || name.contains(filter!) {\n'
            '    currentTestName = name\n'
            '    let before = recordedFailures.count\n'
            '    let instance = type.init()\n'
            '    do { try instance.setUpWithError(); try await body(instance) } catch { fail("threw \\(error)", 0) }\n'
            '    instance.tearDown()\n'
            '    ran += 1\n'
            '    print(recordedFailures.count == before ? "ok   \\(name)" : "FAIL \\(name)")\n'
            '}\n'
            'for failure in recordedFailures { print("  " + failure) }\n'
            'print("\\(ran) tests, \\(assertionCount) assertions, \\(recordedFailures.count) failures")\n'
            'exit(recordedFailures.isEmpty && ran > 0 ? 0 : 1)\n')


if __name__ == '__main__':
    target = HERE / 'main.swift'
    expected = render()
    if '--check' in sys.argv:
        sys.exit(0 if target.exists() and target.read_text(encoding='utf-8') == expected else 1)
    target.write_text(expected, encoding='utf-8')
